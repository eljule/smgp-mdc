    /**
     * Retrieve all offices dynamically from database or fallback to static catalog.
     *
     * @return array<int, array<string, mixed>>
     */
    public function getAllOffices(): array
    {
        if (class_exists(Office::class) && Schema::hasTable('core_offices')) {
            $dbOffices = Office::with('parent')->orderBy('code')->get();
            if ($dbOffices->isNotEmpty()) {
                return $dbOffices->map(static function (Office $office): array {
                    return [
                        'id' => $office->id,
                        'code' => $office->code,
                        'sigla' => $office->acronym,
                        'name' => $office->name,
                        'parentCode' => $office->parent?->code,
                        'parentName' => $office->parent?->name ?? $office->parent_name,
                        'isSuperior' => $office->level === 1,
                        'sede' => $office->sede ?? 'PALACIO MUNICIPAL (SEDE PRINCIPAL)',
                        'level' => $office->level,
                        'levelLabel' => 'Nivel '.$office->level,
                        'status' => $office->is_active ? 'Activo' : 'Inactivo',
                        'isActive' => (bool) $office->is_active,
                    ];
                })->all();
            }
        }

        return self::OFFICES_DATA;
    }

    /**
     * Execute query search and filtering over the offices catalog.
     *
     * @return array<int, array<string, mixed>>
     */
    public function execute(string $search = '', string $sede = 'TODAS', string $level = 'TODOS'): array
    {
        $filtered = $this->getAllOffices();

        if ($search !== '') {
            $term = mb_strtolower(trim($search));
            $filtered = array_values(array_filter($filtered, static function (array $office) use ($term): bool {
                return str_contains(mb_strtolower($office['code']), $term)
                    || str_contains(mb_strtolower($office['sigla']), $term)
                    || str_contains(mb_strtolower($office['name']), $term)
                    || ($office['parentName'] !== null && str_contains(mb_strtolower($office['parentName']), $term))
                    || str_contains(mb_strtolower($office['sede']), $term);
            }));
        }

        if ($sede !== 'TODAS' && $sede !== '') {
            $filtered = array_values(array_filter($filtered, static function (array $office) use ($sede): bool {
                return $office['sede'] === $sede;
            }));
        }

        if ($level !== 'TODOS' && $level !== '') {
            $targetLevel = (int) $level;
            $filtered = array_values(array_filter($filtered, static function (array $office) use ($targetLevel): bool {
                return (int) $office['level'] === $targetLevel;
            }));
        }

        return $filtered;
    }

    /**
     * Retrieve summary metrics for header cards.
     *
     * @return array<string, int>
     */
    public function getMetrics(): array
    {
        $all = $this->getAllOffices();
        $total = count($all);
        $sedesCount = (class_exists(Sede::class) && Schema::hasTable('core_sedes'))
            ? Sede::where('is_active', true)->count()
            : count(self::SEDES_LIST);
        if ($sedesCount === 0) {
            $sedesCount = count(self::SEDES_LIST);
        }
        $level1Count = count(array_filter($all, static fn (array $o): bool => $o['level'] === 1));
        $subgerenciasCount = count(array_filter($all, static fn (array $o): bool => $o['level'] > 1));

        return [
            'total' => $total,
            'sedes' => $sedesCount,
            'alta_direccion' => $level1Count,
            'subgerencias_unidades' => $subgerenciasCount,
        ];
    }

    /**
     * Retrieve nested hierarchical tree structure of offices.
     *
     * @return array<int, array<string, mixed>>
     */
    public function getTree(): array
    {
        $all = $this->getAllOffices();
        $byCode = [];
        foreach ($all as $item) {
            $item['children'] = [];
            $byCode[$item['code']] = $item;
        }

        $tree = [];
        foreach ($all as $item) {
            $parentCode = $item['parentCode'] ?? null;
            if ($parentCode && isset($byCode[$parentCode])) {
                $byCode[$parentCode]['children'][] = &$byCode[$item['code']];
            } else {
                $tree[] = &$byCode[$item['code']];
            }
        }

        return $tree;
    }

    /**
     * Retrieve the list of institutional sedes.
     *
     * @return array<int, string>
     */
    public function getSedes(): array
    {
        if (class_exists(Sede::class) && Schema::hasTable('core_sedes')) {
            $dbSedes = Sede::where('is_active', true)->orderBy('name')->pluck('name')->all();
            if (! empty($dbSedes)) {
                return $dbSedes;
            }
        }

        return self::SEDES_LIST;
    }
